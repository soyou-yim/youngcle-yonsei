export const TEXTBOOKS = [GRAMMAR_POINTS];

// 연습 기록 회차 ID: book-<교재ID>-<유닛ID>
export const bookSetId = (bookId, unitId) => `book-${bookId}-${unitId}`;

// 회원/관리자 목록용 요약 (문장은 빼고)
export function listTextbooks() {
  return TEXTBOOKS.map(b => ({
    id: b.id,
    title: b.title,
    units: b.units.map(u => ({ id: bookSetId(b.id, u.id), title: u.title, sentenceCount: u.sentences.length, wordCount: u.words.length })),
  }));
}

// 'book-gp-u1' → 피드백 회차와 같은 모양의 세트 (없으면 null)
export function getTextbookSet(setId) {
  const m = /^book-([a-z0-9]+)-([a-z0-9]+)$/i.exec(String(setId || ''));
  if (!m) return null;
  const book = TEXTBOOKS.find(b => b.id === m[1]);
  const unit = book && book.units.find(u => u.id === m[2]);
  if (!unit) return null;
  return { id: setId, title: `${book.title} ${unit.title}`, book: book.id, sentences: unit.sentences, words: unit.words };
}

export const isTextbookSetId = id => /^book-/.test(String(id || ''));
